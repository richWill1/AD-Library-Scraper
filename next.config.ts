import type { NextConfig } from "next";

// Main AdSnoop service config. Previews without Meta credentials forward
// research requests to the main service, which keeps credentials private.
const backend = "https://ad-library-scraper-94t0.onrender.com";
const livePages = {
  "/": "index",
  "/christmas-ads": "christmas",
  "/black-friday-ads": "black-friday",
  "/meta-updates": "meta-updates",
  "/privacy": "privacy",
  "/terms": "terms",
  "/data-deletion": "data-deletion",
};

const nextConfig: NextConfig = {
  async redirects() {
    return Object.entries(livePages).map(([destination, file]) => ({
      source: `/live/${file}.html`,
      destination,
      permanent: true,
    }));
  },
  async headers() {
    return [
      // Insights pages are rebuilt on every deploy; let browsers and the CDN
      // reuse them briefly. Versioned assets can be cached for a long time.
      {
        source: "/insights/:path*",
        headers: [{ key: "Cache-Control", value: "public, max-age=300, stale-while-revalidate=86400" }],
      },
      {
        source: "/insights",
        headers: [{ key: "Cache-Control", value: "public, max-age=300, stale-while-revalidate=86400" }],
      },
      ...["/insights-assets/:path*", "/insights-art/:path*"].map(source => ({
        source,
        headers: [{ key: "Cache-Control", value: "public, max-age=86400, stale-while-revalidate=604800" }],
      })),
      // The generated files are only meant to be reached through /insights.
      {
        source: "/insights-pages/:path*",
        headers: [{ key: "X-Robots-Tag", value: "noindex" }],
      },
      { source: "/tracker", headers: [{ key: "X-Robots-Tag", value: "noindex" }] },
      ...["preview\\.adsnoop\\.co\\.uk", ".*\\.onrender\\.com"].map(value => ({
        source: "/:path*",
        has: [{ type: "host" as const, value }],
        headers: [{ key: "X-Robots-Tag", value: "noindex" }],
      })),
    ];
  },
  async rewrites() {
    // The AdSnoop research app is the homepage.
    const home = [
      ...Object.entries(livePages).map(([source, file]) => ({
        source,
        destination: `/live/${file}.html`,
      })),
      { source: "/tracker", destination: "/live/index.html" },
      // Insights hub: static pages generated by scripts/build-insights.mjs.
      { source: "/insights", destination: "/insights-pages/index.html" },
      { source: "/insights/feed.xml", destination: "/insights-pages/feed.xml" },
      { source: "/insights/category/:category", destination: "/insights-pages/category/:category.html" },
      { source: "/insights/angles", destination: "/insights-pages/angles/index.html" },
      { source: "/insights/angles/:slug", destination: "/insights-pages/angles/:slug.html" },
      { source: "/insights/:slug", destination: "/insights-pages/:slug.html" },
    ];
    // A service with its own Meta token uses its own API routes; a preview
    // without one forwards public research requests to the main service.
    if (process.env.META_ACCESS_TOKEN?.trim() || process.env.RENDER_SERVICE_ID === "srv-db3ufoad0e5s73f5dudg") return { beforeFiles: home, afterFiles: [], fallback: [] };

    return {
      beforeFiles: [
        ...home,
        { source: "/api/ads", destination: "/api/preview-ads" },
        { source: "/api/health", destination: `${backend}/api/health` },
        { source: "/api/media", destination: `${backend}/api/media` },
        { source: "/api/formats", destination: `${backend}/api/formats` },
        { source: "/api/popular", destination: `${backend}/api/popular` },
      ],
      afterFiles: [],
      fallback: [],
    };
  },
};

export default nextConfig;
